import re

text = """
서울중앙병원
성명: 김철수
주민등록번호: 850123-1******
주소: 서울특별시 서초구 반포대로 55, 101동 502호
전화번호: 02-123-4567
"""

# 전화번호 마스킹
text = re.sub(r'\b\d{2,3}-\d{3,4}-\d{4}\b', '***-****-****', text)

# 주민등록번호 마스킹
text = re.sub(r'\b\d{6}-\d{7}\b', '******-*******', text)

# 생년월일 형식 마스킹
text = re.sub(r'\b\d{4}-\d{2}-\d{2}\b', '****-**-**', text)

print(text)